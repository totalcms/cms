<?php

declare(strict_types=1);

namespace TotalCMS\Domain\Builder\Service;

use TotalCMS\Domain\Builder\Data\FrontendInstallOptions;
use TotalCMS\Domain\Builder\Data\FrontendInstallRun;
use TotalCMS\Support\OperationResult;
use TotalCMS\Support\PathResolver;

/**
 * Installs the Vite asset pipeline at a project's root: `package.json`,
 * `vite.config.js`, `css/`, `js/` and `FRONTEND.md`, then builds it. The
 * scaffold ships in `resources/builder/frontend/` and is the same for every
 * starter.
 *
 * Every check runs before the first write, so a refused run changes nothing.
 * A project with a package.json is refused: it already has a setup, whether
 * that's this pipeline or its own, and that setup is not ours to edit.
 */
readonly class BuilderFrontendInstaller
{
	private const AGENTS_OPEN  = '<!-- tcms:frontend -->';
	private const AGENTS_CLOSE = '<!-- /tcms:frontend -->';
	private const CSS_LINE     = "{{ cms.builder.css('css/style.css') }}";
	private const LAYOUT       = 'layouts/default.twig';
	private const VITE_CONFIGS = ['vite.config.js', 'vite.config.mjs', 'vite.config.ts', 'vite.config.cjs'];
	private const SOURCES      = ['css/style.css', 'js/app.js', 'FRONTEND.md'];
	private const IGNORES      = [
		'/node_modules/'  => "# Node packages, installed by `npm install`\n/node_modules/\n",
		'/public/assets/' => "# Vite build output, regenerated by `npm run build`\n/public/assets/\n",
	];

	public function __construct(
		private BuilderTemplatePaths $templates,
		private BuilderFrontendBuild $build,
	) {
	}

	/**
	 * Why this project can't take the pipeline, or null when it can. Writes
	 * nothing, so `builder:init` can ask before it scaffolds a starter.
	 */
	public function check(): ?OperationResult
	{
		$root = PathResolver::projectRoot();

		if (!is_dir($this->scaffoldDir())) {
			return OperationResult::failure('Frontend scaffold missing: ' . $this->scaffoldDir());
		}
		if (!is_file($root . '/composer.json')) {
			return OperationResult::failure('builder:frontend needs a Composer project, and there is no composer.json at ' . $root . '.');
		}
		if (!is_file($root . '/public/index.php')) {
			return OperationResult::failure('builder:frontend needs the root layout, with Total CMS at public/index.php. A subpath install leaves public/ for your own frontend.');
		}
		if ($this->hasLegacyFrontend($root)) {
			return OperationResult::failure('This project already has a frontend/ pipeline, and it still works. To move to the new layout, follow "Moving from frontend/" in the docs. Nothing was changed.');
		}

		if (is_file($root . '/package.json')) {
			return OperationResult::failure('This project already has a package.json, so nothing was changed. If this pipeline is already installed, run `npm run build`. To add Vite to your own setup, follow "Adding Vite to an Existing Project" in the docs.');
		}

		return $this->checkAssets($root);
	}

	public function install(FrontendInstallOptions $options = new FrontendInstallOptions()): OperationResult
	{
		$refused = $this->check();
		if ($refused instanceof OperationResult) {
			return $refused;
		}

		$run = new FrontendInstallRun(PathResolver::projectRoot(), $options->dryRun);

		$run->write('package.json', $this->scaffoldFile('package.json'));
		$this->writeViteConfig($run);
		$this->writeSources($run);
		$this->writeGitignore($run);
		$this->writeLayout($run);
		$this->writeAgents($run);

		if ($run->failed !== []) {
			return OperationResult::failure('Could not write: ' . implode(', ', $run->failed), null, $run->toArray());
		}
		if ($options->dryRun) {
			$files = $run->written === [] ? 'nothing' : implode(', ', $run->written);

			return OperationResult::success("Dry run. Nothing was changed. Would write: {$files}", $run->toArray());
		}

		return $this->finish($run, $options);
	}

	// Checks
	// -------------------------

	private function hasLegacyFrontend(string $root): bool
	{
		foreach (self::VITE_CONFIGS as $name) {
			if (is_file("{$root}/frontend/{$name}")) {
				return true;
			}
		}

		return false;
	}

	/**
	 * The first build wipes public/assets/. Files there with no manifest beside
	 * them are someone's source, such as a starter's committed theme, not build
	 * output.
	 */
	private function checkAssets(string $root): ?OperationResult
	{
		$assets = $root . '/public/assets';
		if (!is_dir($assets) || is_file($assets . '/manifest.json') || is_file($assets . '/.vite/manifest.json')) {
			return null;
		}

		$found = [];
		$files = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($assets, \FilesystemIterator::SKIP_DOTS));
		foreach ($files as $file) {
			if ($file->isFile() && $file->getFilename() !== '.DS_Store') {
				$found[] = substr($file->getPathname(), strlen($root) + 1);
			}
		}
		if ($found === []) {
			return null;
		}

		sort($found);
		$more = count($found) > 8 ? sprintf("\n  ...and %d more", count($found) - 8) : '';

		return OperationResult::failure(
			"public/assets/ holds files that the build would delete:\n  " . implode("\n  ", array_slice($found, 0, 8)) . $more
				. "\nMove them to css/ and import them from css/style.css, or put them somewhere else, then run this again. Nothing was changed.",
			null,
			['blocked' => $found],
		);
	}

	// Files
	// -------------------------

	private function writeViteConfig(FrontendInstallRun $run): void
	{
		$existing = $this->existingViteConfig($run->root);

		if ($existing === null) {
			$run->write('vite.config.js', $this->scaffoldFile('vite.config.js'));

			return;
		}

		$run->skipped[] = $existing;
		$source         = (string)file_get_contents("{$run->root}/{$existing}");
		if (!str_contains($source, 'publicDir')) {
			$run->notes[] = "{$existing} was kept, but it doesn't set publicDir. Set publicDir: false, or Vite will copy public/ into the build.";
		}
		if (!str_contains($source, 'manifest')) {
			$run->notes[] = "{$existing} was kept, but it doesn't write a manifest. Set build.manifest: 'manifest.json' so {{ cms.builder.css() }} can find hashed files.";
		}
	}

	private function existingViteConfig(string $root): ?string
	{
		foreach (self::VITE_CONFIGS as $name) {
			if (is_file("{$root}/{$name}")) {
				return $name;
			}
		}

		return null;
	}

	private function writeSources(FrontendInstallRun $run): void
	{
		foreach (self::SOURCES as $relative) {
			if (is_file("{$run->root}/{$relative}")) {
				$run->skipped[] = $relative;
			} else {
				$run->write($relative, $this->scaffoldFile($relative));
			}
		}
	}

	private function writeGitignore(FrontendInstallRun $run): void
	{
		$path     = $run->root . '/.gitignore';
		$existing = is_file($path) ? (string)file_get_contents($path) : '';
		$lines    = array_map(trim(...), preg_split('/\R/', $existing) ?: []);
		$addition = '';

		foreach (self::IGNORES as $entry => $block) {
			if (in_array($entry, $lines, true)) {
				$run->gitignore[$entry] = 'present';
			} else {
				$run->gitignore[$entry] = 'added';
				$addition .= "\n" . $block;
			}
		}

		if ($addition !== '') {
			$run->write('.gitignore', rtrim($existing) === '' ? ltrim($addition) : rtrim($existing) . "\n" . $addition);
		}
	}

	/**
	 * A stylesheet nothing loads is the bug this prevents. Only a layout with
	 * no stylesheet of its own is touched.
	 */
	private function writeLayout(FrontendInstallRun $run): void
	{
		$path    = $this->templates->writePath(self::LAYOUT);
		$display = $run->relative($path);

		if (!is_file($path)) {
			$run->layout  = 'missing';
			$run->notes[] = "No {$display}. Add " . self::CSS_LINE . ' to your layout.';

			return;
		}

		$layout = (string)file_get_contents($path);

		if (str_contains($layout, "cms.builder.css('css/style.css')") || str_contains($layout, 'cms.builder.css("css/style.css")')) {
			$run->layout = 'present';
		} elseif (str_contains($layout, 'cms.builder.css(') || preg_match('/<link[^>]+stylesheet/i', $layout) === 1) {
			$run->layout  = 'kept';
			$run->notes[] = 'Your layout already loads a stylesheet, so it was left alone. Add ' . self::CSS_LINE . ' when you want the built CSS.';
		} else {
			$this->addStylesheet($run, $path, $layout);
		}
	}

	private function addStylesheet(FrontendInstallRun $run, string $path, string $layout): void
	{
		$count   = 0;
		$updated = preg_replace('/^([ \t]*)(\{% block head %\}|<\/head>)/m', '$1' . self::CSS_LINE . "\n" . '$1$2', $layout, 1, $count);

		if ($count !== 1 || !is_string($updated)) {
			$run->layout  = 'manual';
			$run->notes[] = 'Could not find where to add the stylesheet. Add ' . self::CSS_LINE . ' to your layout.';

			return;
		}

		$run->layout = 'added';
		$run->write($path, $updated);
	}

	/** AGENTS.md: state what this project is, in a block that is ours to rewrite. */
	private function writeAgents(FrontendInstallRun $run): void
	{
		$path = $run->root . '/AGENTS.md';
		if (!is_file($path)) {
			return;
		}

		$block = self::AGENTS_OPEN . "\n## Frontend assets\n\n"
			. "This site builds its CSS and JS with Vite, from the project root. See `FRONTEND.md`.\n\n"
			. "- Edit `css/` and `js/`, then run `npm run build`.\n"
			. "- `public/assets/` is build output, wiped on every build. Don't edit it or add files there.\n"
			. "- Add packages with `npm install` and import them from `css/style.css`.\n"
			. self::AGENTS_CLOSE . "\n";

		$agents  = (string)file_get_contents($path);
		$updated = $this->placeAgentsBlock($agents, $block);

		$run->agents = $updated === $agents ? 'present' : 'updated';
		if ($updated !== $agents) {
			$run->write('AGENTS.md', $updated);
		}
	}

	private function placeAgentsBlock(string $agents, string $block): string
	{
		$pattern = '/' . preg_quote(self::AGENTS_OPEN, '/') . '.*?' . preg_quote(self::AGENTS_CLOSE, '/') . '\n?/s';

		if (preg_match($pattern, $agents) === 1) {
			return (string)preg_replace_callback($pattern, static fn (): string => $block, $agents);
		}
		if (str_contains($agents, "## Project layout\n")) {
			return str_replace("## Project layout\n", $block . "\n## Project layout\n", $agents);
		}

		return rtrim($agents) . "\n\n" . $block;
	}

	// Build
	// -------------------------

	private function finish(FrontendInstallRun $run, FrontendInstallOptions $options): OperationResult
	{
		$next = 'Installed. Next: npm install && npm run build';
		if (!$options->build) {
			return OperationResult::success($next, $run->toArray());
		}

		$build = $this->build->run($run->root, $options->onStep);
		if (!$build->success) {
			return OperationResult::failure($build->message, null, $run->toArray());
		}

		$run->built = (bool)($build->data['built'] ?? false);
		if (!$run->built) {
			$run->notes[] = (string)($build->data['note'] ?? '');

			return OperationResult::success($next, $run->toArray());
		}

		return OperationResult::success('Done. Your CSS and JS are built into public/assets/. See FRONTEND.md.', $run->toArray());
	}

	private function scaffoldFile(string $relative): string
	{
		return (string)file_get_contents($this->scaffoldDir() . '/' . $relative);
	}

	private function scaffoldDir(): string
	{
		return PathResolver::packageRoot() . '/resources/builder/frontend';
	}
}
